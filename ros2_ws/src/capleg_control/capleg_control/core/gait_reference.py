def _wrap(phi):
    return phi - math.floor(phi)


def fourier(name, phi, deriv=0):
    """Evaluate a Fourier reference (deg) or its 1st / 2nd derivative w.r.t. phase (deg per unit phase^n)."""
    c = FOURIER[name]
    nh = (len(c) - 1) // 2
    phi = _wrap(phi)
    if deriv == 0:
        v = c[0]
        for h in range(1, nh + 1):
            w = 2.0 * math.pi * h
            v += c[2 * h - 1] * math.cos(w * phi) + c[2 * h] * math.sin(w * phi)
        return v
    v = 0.0
    for h in range(1, nh + 1):
        w = 2.0 * math.pi * h
        if deriv == 1:
            v += -c[2 * h - 1] * w * math.sin(w * phi) + c[2 * h] * w * math.cos(w * phi)
        else:
            v += -w * w * (c[2 * h - 1] * math.cos(w * phi) + c[2 * h] * math.sin(w * phi))
    return v


def table(name, phi):
    """Linear interpolation in a shape-preserving table."""
    t = TABLES[name]
    x = _wrap(phi) * (len(t) - 1)
    i = int(x)
    if i >= len(t) - 1:
        return t[-1]
    f = x - i
    return t[i] * (1.0 - f) + t[i + 1] * f


def angles_deg(phi):
    """Reference (thigh, knee, ankle, toe) angles in degrees at gait phase phi."""
    return (fourier('thigh', phi), fourier('knee', phi), fourier('ankle', phi), table('toe', phi))


def angles_rad(phi):
    return tuple(math.radians(a) for a in angles_deg(phi))


def velocities_rad(phi, stride_time):
    """Reference joint velocities (rad/s) for a given stride time (s)."""
    k = math.radians(1.0) / stride_time
    return (fourier('thigh', phi, 1) * k, fourier('knee', phi, 1) * k, fourier('ankle', phi, 1) * k)
